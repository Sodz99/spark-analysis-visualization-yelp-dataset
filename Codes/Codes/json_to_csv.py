import json
import pandas as pd

def process_business_json(json_path, csv_path, chunk_size=10000):

    all_data = []
    data = []
    with open(json_path, 'r') as json_file:
        for i, line in enumerate(json_file):
            record = json.loads(line)
            # Flatten hours
            if 'hours' in record:
                for day, times in record['hours'].items():
                    record[f'hours_{day}_open'] = times['open']
                    record[f'hours_{day}_close'] = times['close']
                del record['hours']
            # Flatten attributes
            if 'attributes' in record:
                for attr, value in record['attributes'].items():
                    if isinstance(value, dict):
                        for sub_attr, sub_value in value.items():
                            record[f'attributes_{attr}_{sub_attr}'] = sub_value
                    else:
                        record[f'attributes_{attr}'] = value
                del record['attributes']
            data.append(record)
            all_data.append(record)
            if (i + 1) % chunk_size == 0:
                df = pd.DataFrame(data)
                df.to_csv(csv_path, mode='a', index=False, header=not pd.io.common.file_exists(csv_path))
                data = []
        if data:
            df = pd.DataFrame(data)
            df.to_csv(csv_path, mode='a', index=False, header=not pd.io.common.file_exists(csv_path))

    # Create the final DataFrame with all data
    final_df = pd.DataFrame(all_data)
    return final_df

